const dict = { exact, patterns };
const compiled = patterns.map(([s, r]) => [new RegExp(s), r]);

/** `s` in language `lang`: the dictionary's own words, or `s` as it is. */
function tr(lang, s, extra) {
  if (lang !== 'tr' || typeof s !== 'string' || !s) return s;
  if (extra && extra[s]) return extra[s];
  if (Object.prototype.hasOwnProperty.call(exact, s)) return exact[s];
  let out = s;
  for (const [re, rep] of compiled) if (re.test(out)) out = out.replace(re, rep);
  return out;
}

